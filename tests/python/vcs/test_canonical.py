def test_merge_verdicts_unions_across_bodies() -> None:
    reviews = [
        {"id": 1, "body": build_verdicts_marker({"fp-a": "dismissed"})},
        {"id": 2, "body": build_verdicts_marker({"fp-b": "fixed"})},
    ]
    assert merge_verdicts(reviews) == {"fp-a": "dismissed", "fp-b": "fixed"}


def test_merge_verdicts_recurred_tombstone_in_older_body_wins_over_stale_fixed_in_newer() -> None:
    """The newest review's marker only ever reflects the state *as of when it
    was written* -- a "fixed" entry seeded from an even-older body before the
    write side's union-seeding fix would otherwise resurrect a finding this
    run already flagged as recurred. Folding bodies in ascending id order
    means the later "recurred" write wins regardless of which review it
    physically landed on."""
    reviews = [
        {"id": 1, "body": build_verdicts_marker({"fp-a": "fixed"})},
        {"id": 2, "body": build_verdicts_marker({"fp-a": "recurred"})},
    ]
    assert merge_verdicts(reviews) == {"fp-a": "recurred"}
    # Order in the input sequence must not matter -- only review id order.
    reversed_input = list(reversed(reviews))
    assert merge_verdicts(reversed_input) == {"fp-a": "recurred"}


def test_merge_verdicts_empty() -> None:
    assert merge_verdicts([]) == {}


