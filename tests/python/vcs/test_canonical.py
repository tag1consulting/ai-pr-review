def _thread_node(
    *,
    body: str,
    author: str = "github-actions",
    thread_id: str = "th1",
    comment_id: int = 100,
    review_id: int = 10,
    is_resolved: bool = False,
    is_outdated: bool = False,
    path: str = "app.py",
    line: int | None = 10,
    original_line: int | None = None,
    start_line: int | None = None,
) -> dict:
    return {
        "id": thread_id,
        "isResolved": is_resolved,
        "isOutdated": is_outdated,
        "path": path,
        "line": line,
        "originalLine": original_line,
        "startLine": start_line,
        "comments": {
            "nodes": [
                {
                    "databaseId": comment_id,
                    "body": body,
                    "author": {"login": author},
                    "pullRequestReview": {"databaseId": review_id},
                }
            ]
        },
    }


def test_parse_prior_thread_reads_meta_marker() -> None:
    f = _finding(file="app.py", line=10, severity="High", category="secret")
    fp = fingerprint(f)
    marker = build_inline_meta_marker(fingerprint=fp, category="secret", severity="High")
    body = f"🔴 **[High]** [code-reviewer] leaked key\n<!-- ai-pr-review-inline -->\n{marker}"
    node = _thread_node(body=body)

    thread = parse_prior_thread(node, bot_login="github-actions")
    assert thread is not None
    assert thread.fingerprint == fp
    assert thread.category == "secret"
    assert thread.severity == "High"
    assert thread.path == "app.py"
    assert thread.line == 10


def test_parse_prior_thread_not_owned_by_us_returns_none() -> None:
    node = _thread_node(body="some comment", author="someone-else")
    assert parse_prior_thread(node, bot_login="github-actions") is None


def test_parse_prior_thread_legacy_falls_back_to_header_severity() -> None:
    body = "🔴 **[High]** [code-reviewer] leaked key\n<!-- ai-pr-review-inline -->"
    node = _thread_node(body=body)

    thread = parse_prior_thread(node, bot_login="github-actions")
    assert thread is not None
    assert thread.severity == "High"
    assert thread.category is None
    assert thread.fingerprint is None


def test_parse_prior_thread_legacy_recovers_fingerprint_via_id_map_bodies() -> None:
    f = _finding("leaked key", file="app.py", line=10, source="code-reviewer", severity="High")
    fp = fingerprint(f)
    from ai_pr_review.vcs.marker import build_id_map_marker

    id_map_body = "## AI Review Findings\n" + build_id_map_marker({fp: 3})
    body = "🔴 **[High]** **[F3]** [code-reviewer] leaked key\n<!-- ai-pr-review-inline -->"
    node = _thread_node(body=body)

    thread = parse_prior_thread(
        node, bot_login="github-actions", id_map_bodies=[id_map_body]
    )
    assert thread is not None
    assert thread.fingerprint == fp
    assert thread.finding_id == 3


