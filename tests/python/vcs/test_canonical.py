def test_classify_no_match_is_new() -> None:
    f = _finding(file="app.py", line=100)
    result = classify(f, verdicts={}, all_threads=[])
    assert result.kind == "new"
    assert result.thread is None


def test_classify_exact_dismissed_match_suppresses() -> None:
    f = _finding(file="app.py", line=10)
    fp = fingerprint(f)
    result = classify(f, verdicts={fp: "dismissed"}, all_threads=[])
    assert result.kind == "suppressed"


def test_classify_fuzzy_dismissed_match_compatible_category_and_severity_suppresses() -> None:
    dismissed = _finding("nit", file="app.py", line=10, severity="Low", category="lint")
    dismissed_fp = fingerprint(dismissed)
    thread = _thread(fp=dismissed_fp, severity="Low", category="lint", is_resolved=True)
    new_finding = _finding("similar nit", file="app.py", line=12, severity="Low", category="lint")

    result = classify(
        new_finding, verdicts={dismissed_fp: "dismissed"}, all_threads=[thread]
    )
    assert result.kind == "suppressed"


def test_classify_fuzzy_dismissed_match_incompatible_category_falls_through() -> None:
    """This is the exact information-loss case the per-comment metadata
    marker exists to prevent: a dismissed Low lint nit two lines away must
    never silently swallow an unrelated new secret-leak finding."""
    dismissed = _finding("nit", file="app.py", line=10, severity="Low", category="lint")
    dismissed_fp = fingerprint(dismissed)
    thread = _thread(fp=dismissed_fp, severity="Low", category="lint", is_resolved=True)
    new_finding = _finding(
        "leaked API key", file="app.py", line=11, severity="Critical", category="secret"
    )

    result = classify(
        new_finding, verdicts={dismissed_fp: "dismissed"}, all_threads=[thread]
    )
    assert result.kind == "new"


def test_classify_fuzzy_dismissed_match_higher_severity_falls_through() -> None:
    dismissed = _finding("nit", file="app.py", line=10, severity="Low", category="other")
    dismissed_fp = fingerprint(dismissed)
    thread = _thread(fp=dismissed_fp, severity="Low", category="other", is_resolved=True)
    new_finding = _finding("real bug", file="app.py", line=11, severity="Critical", category="other")

    result = classify(
        new_finding, verdicts={dismissed_fp: "dismissed"}, all_threads=[thread]
    )
    assert result.kind == "new"


def test_classify_fuzzy_dismissed_match_unrecoverable_severity_never_suppresses() -> None:
    """A body-level dismissed finding has no comment, hence no metadata
    marker -- its severity is permanently unrecoverable and must never be
    treated as an escalation waiver. Only an exact fingerprint match can
    suppress a body-level dismissal."""
    dismissed = _finding("body-level nit", file="app.py", line=10, severity="Low")
    dismissed_fp = fingerprint(dismissed)
    new_finding = _finding("nearby issue", file="app.py", line=11, severity="Low")

    result = classify(new_finding, verdicts={dismissed_fp: "dismissed"}, all_threads=[])
    assert result.kind == "new"


def test_classify_exact_fixed_match_is_recurred_with_thread() -> None:
    f = _finding(file="app.py", line=10, severity="High")
    fp = fingerprint(f)
    thread = _thread(fp=fp, is_resolved=True, severity="High")
    result = classify(f, verdicts={fp: "fixed"}, all_threads=[thread])
    assert result.kind == "recurred"
    assert result.thread is thread


def test_classify_exact_fixed_match_body_level_recurred_without_thread() -> None:
    f = _finding(file="app.py", line=10)
    fp = fingerprint(f)
    result = classify(f, verdicts={fp: "fixed"}, all_threads=[])
    assert result.kind == "recurred"
    assert result.thread is None


def test_classify_fuzzy_only_fixed_match_is_not_recurred() -> None:
    """Row: 'matches a fixed thread, fuzzy-only (not exact) match' -> falls
    through as genuinely new (or update/escalate if it also fuzzy-matches an
    *open* thread) -- the recurrence check is deliberately exact-only."""
    fixed = _finding("original", file="app.py", line=10)
    fixed_fp = fingerprint(fixed)
    reworded = _finding("reworded text", file="app.py", line=11)

    result = classify(reworded, verdicts={fixed_fp: "fixed"}, all_threads=[])
    assert result.kind == "new"


